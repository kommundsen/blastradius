//! The workspace format, written for whoever is about to edit it — in
//! practice an agent modelling a repository for the first time.
//!
//! It exists because `spec/model-format.md` lives in *this* repository and
//! nowhere near a user's. Nothing in a fresh `blastradius init` said what
//! valid YAML looks like, so the first agent to try inferred the schema from
//! a sample file and then looped on validation errors (docs/roadmap.md,
//! first-user findings). Served by the `model_format` MCP tool and embedded
//! in the generated skill, so it is in reach before the first tool call.
//!
//! `spec/model-format.md` stays normative; this is the same rules, compressed
//! to what someone writing a model actually has to know. `EXAMPLE` is parsed
//! and validated by tests/format_ref.rs, so it cannot rot into something that
//! does not load.

/// A complete workspace, file by file: manifest, context, one system, a view,
